import fs from 'node:fs/promises';
import {createHash} from 'node:crypto';
import mysql from 'mysql2/promise';
import pg from 'pg';
import {connectionConfig} from '../server/config/database.js';
import {postgresConfig} from '../server/config/postgres.js';
import {TABLES} from './import-mysql.mjs';

const identifier=name=>{if(!/^[a-z][a-z0-9_]*$/.test(name))throw new Error('Invalid SQL identifier');return '"'+name+'"';};
const canonical=value=>Array.isArray(value)?value.map(canonical):value&&typeof value==='object'&&!(value instanceof Date)?Object.fromEntries(Object.keys(value).sort().map(k=>[k,canonical(value[k])])):value;
const digest=value=>createHash('sha256').update(JSON.stringify(canonical(value))).digest('hex');
export async function exportMysql(file){
 const c=await mysql.createConnection(connectionConfig());
 try{
  await c.query('SET TRANSACTION ISOLATION LEVEL REPEATABLE READ');
  await c.query('START TRANSACTION WITH CONSISTENT SNAPSHOT, READ ONLY');
  const [columns]=await c.query('SELECT TABLE_NAME,COLUMN_NAME,COLUMN_TYPE,IS_NULLABLE,COLUMN_DEFAULT,COLUMN_KEY,EXTRA FROM information_schema.COLUMNS WHERE TABLE_SCHEMA=DATABASE() ORDER BY TABLE_NAME,ORDINAL_POSITION');
  const [foreignKeys]=await c.query('SELECT k.TABLE_NAME,k.COLUMN_NAME,k.REFERENCED_TABLE_NAME,k.REFERENCED_COLUMN_NAME,k.CONSTRAINT_NAME,r.DELETE_RULE,r.UPDATE_RULE FROM information_schema.KEY_COLUMN_USAGE k JOIN information_schema.REFERENTIAL_CONSTRAINTS r ON r.CONSTRAINT_SCHEMA=k.CONSTRAINT_SCHEMA AND r.CONSTRAINT_NAME=k.CONSTRAINT_NAME AND r.TABLE_NAME=k.TABLE_NAME WHERE k.TABLE_SCHEMA=DATABASE() AND k.REFERENCED_TABLE_NAME IS NOT NULL ORDER BY k.TABLE_NAME,k.CONSTRAINT_NAME,k.ORDINAL_POSITION');
  const [indexes]=await c.query('SELECT TABLE_NAME,INDEX_NAME,NON_UNIQUE,COLUMN_NAME,SEQ_IN_INDEX FROM information_schema.STATISTICS WHERE TABLE_SCHEMA=DATABASE() ORDER BY TABLE_NAME,INDEX_NAME,SEQ_IN_INDEX');
  const data={},ddl={};
  if(new Set(columns.map(c=>c.TABLE_NAME)).size!==TABLES.length||columns.some(c=>!TABLES.includes(c.TABLE_NAME)))throw new Error('Unexpected source schema; review migration before exporting.');
  for(const table of TABLES){
   const keys=columns.filter(c=>c.TABLE_NAME===table&&c.COLUMN_KEY==='PRI').map(c=>'`'+c.COLUMN_NAME+'`');
   [data[table]]=await c.query('SELECT * FROM `'+table+'`'+(keys.length?' ORDER BY '+keys.join(','):''));
   const [create]=await c.query('SHOW CREATE TABLE `'+table+'`');ddl[table]=create[0]['Create Table'];
  }
  await c.commit();
  const snapshot={version:1,createdAt:new Date().toISOString(),columns,foreignKeys,indexes,ddl,data};
  const content=JSON.stringify(snapshot);await fs.writeFile(file,content,{flag:'wx',mode:0o600});
  return {file,sha256:createHash('sha256').update(content).digest('hex'),counts:Object.fromEntries(TABLES.map(t=>[t,data[t].length]))};
 }catch(e){await c.rollback().catch(()=>{});throw e;}finally{await c.end();}
}
function sqlType(column){
 const type=column.COLUMN_TYPE.toLowerCase();
 if(type==='tinyint(1)')return 'BOOLEAN';
 if(type.startsWith('bigint'))return 'BIGINT';
 if(type.startsWith('int'))return type.includes('unsigned')?'BIGINT':'INTEGER';
 if(type.startsWith('smallint'))return type.includes('unsigned')?'INTEGER':'SMALLINT';
 if(type.startsWith('tinyint'))return 'SMALLINT';
 if(/^decimal\(\d+,\d+\)$/.test(type))return type.toUpperCase();
 if(/^(var)?char\(\d+\)$/.test(type))return type.toUpperCase();
 if(type==='text'||type.startsWith('enum('))return 'TEXT';
 if(type==='json')return 'JSONB';
 if(/^(datetime|timestamp)/.test(type))return 'TIMESTAMPTZ(3)';
 throw new Error('Unsupported source SQL type '+type);
}
export function postgresSchema(snapshot){
 const statements=['-- PostgreSQL schema converted from the live MySQL metadata. No production secrets.'];
 for(const table of TABLES){
  const cols=snapshot.columns.filter(c=>c.TABLE_NAME===table);const lines=[];
  for(const c of cols){
   let line=identifier(c.COLUMN_NAME)+' '+sqlType(c);
   if(c.EXTRA.includes('auto_increment'))line+=' GENERATED BY DEFAULT AS IDENTITY';
   else if(c.COLUMN_DEFAULT!==null){
    const d=String(c.COLUMN_DEFAULT);
    line+=' DEFAULT '+(/^current_timestamp(?:\(\d*\))?$/i.test(d)?'CURRENT_TIMESTAMP':c.COLUMN_TYPE==='tinyint(1)'?(d==='0'?'FALSE':'TRUE'):/^(bigint|int|smallint|tinyint|decimal)/i.test(c.COLUMN_TYPE)&&/^-?\d+(\.\d+)?$/.test(d)?d:"'"+d.replaceAll("'","''")+"'");
   }
   if(c.IS_NULLABLE==='NO')line+=' NOT NULL';
   if(c.COLUMN_TYPE.startsWith('enum('))line+=' CHECK ('+identifier(c.COLUMN_NAME)+' IN ('+c.COLUMN_TYPE.slice(5,-1)+'))';
   if(c.COLUMN_TYPE.includes('unsigned'))line+=' CHECK ('+identifier(c.COLUMN_NAME)+'>=0)';
   lines.push(line);
  }
  const primary=cols.filter(c=>c.COLUMN_KEY==='PRI').map(c=>identifier(c.COLUMN_NAME));if(primary.length)lines.push('PRIMARY KEY ('+primary.join(',')+')');
  statements.push('CREATE TABLE '+identifier(table)+' (\n  '+lines.join(',\n  ')+'\n);');
 }
 const indexes=new Map();
 for(const i of snapshot.indexes){if(i.INDEX_NAME==='PRIMARY')continue;const key=i.TABLE_NAME+'/'+i.INDEX_NAME;if(!indexes.has(key))indexes.set(key,[]);indexes.get(key).push(i);}
 for(const list of indexes.values()){
  const i=list[0],name=(i.TABLE_NAME+'_'+i.INDEX_NAME).slice(0,63);
  statements.push('CREATE '+(!i.NON_UNIQUE?'UNIQUE ':'')+'INDEX '+identifier(name)+' ON '+identifier(i.TABLE_NAME)+' ('+list.map(i=>identifier(i.COLUMN_NAME)).join(',')+');');
 }
 const constraints=new Map();for(const f of snapshot.foreignKeys){const key=f.TABLE_NAME+'/'+f.CONSTRAINT_NAME;if(!constraints.has(key))constraints.set(key,[]);constraints.get(key).push(f);}
 for(const list of constraints.values()){
  const f=list[0];
  const rule=value=>{if(!['CASCADE','RESTRICT','NO ACTION','SET NULL'].includes(value))throw new Error('Unsupported foreign key action');return value;};
  // Old snapshots can recover the delete action from their original CREATE TABLE.
  const originalLine=snapshot.ddl?.[f.TABLE_NAME]?.split('\n').find(line=>line.includes('`'+f.CONSTRAINT_NAME+'`'))||'';
  const deletion=f.DELETE_RULE||originalLine.match(/ON DELETE (CASCADE|RESTRICT|SET NULL|NO ACTION)/)?.[1]||'NO ACTION';
  statements.push('ALTER TABLE '+identifier(f.TABLE_NAME)+' ADD CONSTRAINT '+identifier(f.CONSTRAINT_NAME)+' FOREIGN KEY ('+list.map(f=>identifier(f.COLUMN_NAME)).join(',')+') REFERENCES '+identifier(f.REFERENCED_TABLE_NAME)+' ('+list.map(f=>identifier(f.REFERENCED_COLUMN_NAME)).join(',')+') ON DELETE '+rule(deletion)+' ON UPDATE '+rule(f.UPDATE_RULE||'NO ACTION')+' DEFERRABLE INITIALLY DEFERRED;');
 }
 statements.push('CREATE UNIQUE INDEX users_email_lower_unique ON users (lower(email));');
 statements.push('ALTER TABLE restaurant_dishes ADD CONSTRAINT ck_rd_price CHECK (price_vnd IS NULL OR price_vnd>=0);');
 statements.push('ALTER TABLE recipes ADD CONSTRAINT ck_recipe_servings CHECK (base_servings BETWEEN 1 AND 12);');
 statements.push('ALTER TABLE recipe_ingredients ADD CONSTRAINT ck_ingredient_amount CHECK ((amount_text IS NOT NULL AND amount_min IS NULL AND amount_max IS NULL) OR (amount_text IS NULL AND amount_min IS NOT NULL AND amount_min>0 AND unit IS NOT NULL AND (amount_max IS NULL OR amount_max>=amount_min)));');
 return statements.join('\n\n');
}
function expectedRows(snapshot,table){
 const bools=new Set(snapshot.columns.filter(c=>c.TABLE_NAME===table&&c.COLUMN_TYPE==='tinyint(1)').map(c=>c.COLUMN_NAME));
 return snapshot.data[table].map(row=>Object.fromEntries(Object.entries(row).map(([key,value])=>[key,value==null?null:bools.has(key)?!!value:value])));
}
export async function importPostgres(snapshot,url,{schema='public'}={}){
 identifier(schema);
 const c=new pg.Client(postgresConfig({DATABASE_URL:url,PG_SCHEMA:schema}));await c.connect();
 try{
  await c.query('BEGIN');await c.query("SELECT pg_advisory_xact_lock(hashtext('hnag-neon-migration'))");
  const existing=await c.query('SELECT tablename FROM pg_tables WHERE schemaname=$1',[schema]);
  if(existing.rows.length)throw new Error('Destination is not empty. Refusing to overwrite existing PostgreSQL data.');
  await c.query(postgresSchema(snapshot));
  await c.query('SET CONSTRAINTS ALL DEFERRED');
  for(const table of TABLES){
   const cols=snapshot.columns.filter(c=>c.TABLE_NAME===table);const fields=cols.map(c=>identifier(c.COLUMN_NAME));
   const sourceRows=expectedRows(snapshot,table);
   for(let offset=0;offset<sourceRows.length;offset+=50){
    const batch=sourceRows.slice(offset,offset+50),params=[];
    const values=batch.map(row=>'('+cols.map(col=>{params.push(col.COLUMN_TYPE==='json'&&row[col.COLUMN_NAME]!==null?JSON.stringify(row[col.COLUMN_NAME]):row[col.COLUMN_NAME]);return '$'+params.length;}).join(',')+')');
    await c.query('INSERT INTO '+identifier(table)+' ('+fields.join(',')+') VALUES '+values.join(','),params);
   }
  }
  const checks=[];
  for(const table of TABLES){
   const keys=snapshot.columns.filter(c=>c.TABLE_NAME===table&&c.COLUMN_KEY==='PRI').map(c=>identifier(c.COLUMN_NAME));
   const {rows}=await c.query('SELECT * FROM '+identifier(table)+(keys.length?' ORDER BY '+keys.join(','):''));
   // SQL collations may order strings differently. Sort by canonical row content
   // for a lossless comparison instead of assuming identical locale ordering.
   const normalize=rows=>rows.map(canonical).map(v=>JSON.stringify(v)).sort();
   const match=digest(normalize(rows))===digest(normalize(expectedRows(snapshot,table)));
   checks.push({table,count:rows.length,match});if(!match)throw new Error('Data verification failed for '+table);
   for(const col of snapshot.columns.filter(col=>col.TABLE_NAME===table&&col.EXTRA.includes('auto_increment'))){
    const max=await c.query('SELECT max('+identifier(col.COLUMN_NAME)+') AS value FROM '+identifier(table));
    await c.query('SELECT setval(pg_get_serial_sequence($1,$2),$3,$4)',[table,col.COLUMN_NAME,max.rows[0].value||1,max.rows[0].value!==null]);
   }
  }
  await c.query('SET CONSTRAINTS ALL IMMEDIATE');await c.query('COMMIT');return checks;
 }catch(e){await c.query('ROLLBACK').catch(()=>{});throw e;}finally{await c.end();}
}
const direct=process.argv[1]?.replaceAll('\\','/').endsWith('/migrate-neon.mjs')||process.argv[1]==='scripts/migrate-neon.mjs';
if(direct){
 try{
  const command=process.argv[2],file=process.argv[3];
  if(command==='export'){if(!file?.startsWith('.env.'))throw new Error('Use a gitignored .env.* snapshot file.');console.log(JSON.stringify(await exportMysql(file)));}
  else if(command==='apply'){
   if(!file?.startsWith('.env.'))throw new Error('Use the private exported snapshot.');
   const snapshot=JSON.parse(await fs.readFile(file,'utf8'));const url=(await fs.readFile('.env.neon-uri','utf8')).trim();
   await fs.mkdir('database/postgres',{recursive:true});await fs.writeFile('database/postgres/schema.sql',postgresSchema(snapshot));
   const checks=await importPostgres(snapshot,url);await fs.writeFile('.env.neon-verification.json',JSON.stringify({verifiedAt:new Date().toISOString(),checks},null,2));console.log(JSON.stringify({verified:true,checks}));
  }else throw new Error('Usage: node --env-file=.env scripts/migrate-neon.mjs export|apply .env.snapshot.json');
 }catch(e){console.error('Migration stopped:',e.code||e.message);process.exitCode=1;}
}
